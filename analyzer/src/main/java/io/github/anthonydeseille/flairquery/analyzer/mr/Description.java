package io.github.anthonydeseille.flairquery.analyzer.mr;

import com.fasterxml.jackson.databind.JsonNode;

import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.regex.Pattern;

/**
 * The merge request of a selected fix: branch, title and a Markdown description built only from what was
 * measured (the proof report) and the evidence bundles: the problem, the change, the proof, what a reviewer
 * should look at, and the related fixes (covered, deferred). Like the reports, it names SQL with placeholders and
 * JSON paths, never data values.
 */
public final class Description {

    public record MergeRequest(String fix, String branch, String title, String body) { }

    static final String BRANCH_PREFIX = "flairquery/";
    static final Pattern CONFIG = Pattern.compile("(^|/)application[^/]*\\.(ya?ml|properties)$");

    static final Map<String, String> KINDS = Map.of(
            "N_PLUS_ONE_LAZY", "N+1 lazy loading",
            "USELESS_EAGER", "useless EAGER",
            "OVER_FETCHING", "over-fetching",
            "IN_MEMORY_PAGINATION", "in-memory pagination",
            "OPEN_IN_VIEW", "open-in-view",
            "MISSING_INDEX", "missing index",
            "SORT_SPILL", "sort spilling to disk");

    private Description() { }

    /**
     * @param report  the fix's proof report
     * @param bundles evidence bundles by finding id (severity), possibly empty
     * @param choices the whole selection, for the related fixes
     */
    public static MergeRequest of(FixEntry fix, JsonNode report, Map<String, JsonNode> bundles, List<Selection.Choice> choices)
            throws IOException {
        return of(fix, report, bundles, choices, null);
    }

    /** @param test its regression test (null: tests not generated, e.g. {@code --tests off}) */
    public static MergeRequest of(FixEntry fix, JsonNode report, Map<String, JsonNode> bundles, List<Selection.Choice> choices,
                                  RegressionTests.Outcome test) throws IOException {
        return new MergeRequest(fix.name(), BRANCH_PREFIX + fix.name(), title(report),
                body(fix, report, bundles, choices, test));
    }

    static String title(JsonNode report) {
        String subject = report.path("subject").asText();
        int more = 0;
        for (JsonNode r : report.path("findingsResolved")) {
            if (!r.path("id").asText().equals(report.path("finding").asText())) more++;
        }
        return "FlairQuery: " + kind(report.path("kind").asText()) + " on " + report.path("endpoint").asText()
                + (subject.isEmpty() ? "" : " (" + subject + ")")
                + (more == 0 ? "" : ", " + more + " more finding" + (more > 1 ? "s" : "") + " resolved");
    }

    static String kind(String kind) {
        return KINDS.getOrDefault(kind, kind.toLowerCase(Locale.ROOT).replace('_', ' '));
    }

    static String body(FixEntry fix, JsonNode report, Map<String, JsonNode> bundles, List<Selection.Choice> choices,
                       RegressionTests.Outcome test) throws IOException {
        StringBuilder md = new StringBuilder();
        md.append("> Opened by FlairQuery from a fix its prover accepted. It is never merged automatically: "
                + "a human review is required.\n\n");

        md.append("## Problem\n\n| Finding | Endpoint | Severity | Measured |\n|---|---|---|---|\n");
        for (JsonNode r : report.path("findingsResolved")) {
            JsonNode b = bundles.get(r.path("id").asText());
            md.append("| ").append(kind(r.path("kind").asText()))
                    .append(r.path("id").asText().equals(report.path("finding").asText()) ? " (target)" : "")
                    .append(" | `").append(r.path("endpoint").asText()).append("` | ")
                    .append(b == null ? "" : b.path("severity").asText()).append(" | ")
                    .append(cell(r.path("title").asText())).append(" |\n");
        }

        Set<String> files = new java.util.LinkedHashSet<>(fix.files());
        md.append("\n## Change\n\n").append(fix.description()).append("\n\n");
        if (test != null && test.test() != null) files.add(appPrefix(files) + test.test().path());
        md.append(fix.llm()
                ? "- Written by an LLM" + (fix.attempt() > 1 ? " (attempt " + fix.attempt() + ", after the prover rejected the previous ones)" : "")
                        + ", then proven like any other fix: review it as a colleague's change.\n"
                : "- Generated by the deterministic template `" + fix.generator() + "`.\n");
        md.append("- Files:\n");
        for (String f : files) md.append("  - `").append(f).append("`\n");

        md.append("\n## Proof\n\nMeasured by the FlairQuery prover on a throw-away copy of the code: the current code and "
                + "this change built and run side by side with the FlairQuery agent on a PostgreSQL database "
                + "(Testcontainers) holding the same data, ").append(report.path("rounds").asInt())
                .append(" rounds alternated, median per endpoint.\n\n| Check | | Detail |\n|---|---|---|\n");
        for (JsonNode c : report.path("checks")) {
            md.append("| ").append(c.path("check").asText()).append(" | ").append(c.path("passed").asBoolean() ? "✅" : "❌")
                    .append(" | ").append(cell(c.path("detail").asText())).append(" |\n");
        }
        md.append("\n| Endpoint | Statements / request | SQL ms / request |\n|---|---|---|\n");
        for (JsonNode e : report.path("endpoints")) {
            JsonNode b = e.path("before");
            JsonNode a = e.path("after");
            boolean target = e.path("target").asBoolean();
            String name = "`" + e.path("endpoint").asText() + "`";
            md.append("| ").append(target ? "**" + name + "**" : name).append(" | ")
                    .append(number(b.path("statementsPerRequest").asDouble())).append(" → ")
                    .append(number(a.path("statementsPerRequest").asDouble())).append(" | ")
                    .append(String.format(Locale.ROOT, "%.1f → %.1f", b.path("sqlMsPerRequest").asDouble(),
                            a.path("sqlMsPerRequest").asDouble()))
                    .append(target || !e.path("sameSql").asBoolean() ? ""
                            : report.path("schemaChanged").asBoolean() ? " (same SQL)" : " (same SQL: noise)")
                    .append(" |\n");
        }
        for (JsonNode p : report.path("plans")) {
            md.append("\nPlan of `").append(cell(p.path("sql").asText())).append("`:\n\n```\nbefore: ")
                    .append(p.path("before").asText()).append("\nafter:  ").append(p.path("after").asText()).append("\n```\n");
        }

        md.append("\n## Regression test\n\n");
        if (test == null) {
            md.append("None: tests were not generated for this run.\n");
        } else if (test.test() == null) {
            md.append("None: ").append(test.missing()).append(".\n");
        } else {
            RegressionTest t = test.test();
            md.append("`").append(t.path()).append("` (added by this change): ").append(t.description()).append("\n\n")
                    .append("Proven before this merge request was opened, with `mvnw test -Dtest=").append(t.simpleName())
                    .append("`:\n\n| Code | Result |\n|---|---|\n")
                    .append("| current (without the fix) | ❌ fails: ").append(cell(test.red() == null ? "" : test.red())).append(" |\n")
                    .append("| with the fix | ✅ passes |\n");
            md.append("\nWritten by an LLM").append(test.attempts() > 1 ? " (attempt " + test.attempts() + ")" : "")
                    .append(", kept only because it was red then green: its data set and thresholds are worth a look.\n");
        }

        md.append("\n## Review notes\n\n");
        md.append("- The proof covers the requests the prover replayed (JSON compared on each of them), not every use "
                + "of the changed code: check the other callers.\n");
        if (report.path("schemaChanged").asBoolean()) {
            md.append("- Changes the database schema: check the migration runs as expected in every environment "
                    + "(an index built `CONCURRENTLY` runs outside a transaction).\n");
        }
        if (files.stream().anyMatch(f -> CONFIG.matcher(f).find())) {
            md.append("- Changes the application's configuration: it applies to the whole application, not only to "
                    + "the endpoints measured.\n");
        }
        if (fix.llm()) {
            md.append("- LLM-written: the proof shows it keeps the responses and costs less; readability, naming and "
                    + "style are for you to judge.\n");
        }

        List<String> related = new ArrayList<>();
        for (Selection.Choice c : choices) {
            if (!c.related().contains(fix.name())) continue;
            if (c.decision() == Selection.Decision.REDUNDANT) {
                related.add("- `" + c.fix().name() + "` was not opened: every finding it resolves is resolved by this change.");
            } else if (c.decision() == Selection.Decision.DEFERRED) {
                related.add("- `" + c.fix().name() + "` waits for this one: " + c.why()
                        + ". It will be generated and proven again on the code once this is merged.");
            }
        }
        if (!related.isEmpty()) md.append("\n## Related fixes\n\n").append(String.join("\n", related)).append("\n");

        md.append("\n<sub>FlairQuery · fix `").append(fix.name()).append("` · findings ")
                .append(String.join(", ", report.path("findingsResolved").findValuesAsText("id").stream()
                        .map(id -> "`" + id + "`").toList()))
                .append("</sub>\n");
        return md.toString();
    }

    /** The application directory prefix of the fix's files ({@code demo-app/}), from the first changed file. */
    static String appPrefix(Set<String> files) {
        for (String f : files) {
            int src = f.indexOf("src/");
            if (src >= 0) return f.substring(0, src);
        }
        return "";
    }

    static String number(double n) {
        return n == Math.rint(n) ? String.valueOf((long) n) : String.format(Locale.ROOT, "%.2f", n);
    }

    static String cell(String s) {
        return s.replace("|", "\\|").replace("\n", " ");
    }
}
