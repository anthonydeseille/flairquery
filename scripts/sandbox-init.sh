#!/usr/bin/env bash
# Creates or refreshes the public sandbox repository of the demo app, where FlairQuery opens its pull requests
# (phase 5): the demo app at the repository's root, the Maven wrapper, a README saying what the repository is, and
# a CI that runs the demo's tests (the regression tests added by the pull requests included).
#
#   scripts/sandbox-init.sh OWNER/NAME            create it if missing (public, no issues / wiki), push main
#   scripts/sandbox-init.sh OWNER/NAME --dry-run  only assemble the content in target/sandbox (nothing leaves)
#
# Uses the GitHub CLI (gh auth login) for the repository and for git's credentials. main gets a new commit only when
# the demo changed; the pull requests already open stay as they are (publish refreshes them).
set -euo pipefail

SLUG="${1:?usage: scripts/sandbox-init.sh OWNER/NAME [--dry-run]}"
DRY_RUN="${2:-}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="$ROOT/target/sandbox"
SHA="$(git -C "$ROOT" log -1 --format=%h -- demo-app)"  # last change of the demo, not of FlairQuery
GIT=(git -c credential.helper= -c 'credential.helper=!gh auth git-credential')

rm -rf "$WORK"
if [[ "$DRY_RUN" == "--dry-run" ]]; then
  mkdir -p "$WORK" && git -C "$WORK" init -q --initial-branch=main
else
  if ! gh repo view "$SLUG" >/dev/null 2>&1; then
    gh repo create "$SLUG" --public --disable-issues --disable-wiki \
      --description "Demo app of FlairQuery: the pull requests are opened by FlairQuery, proven, never merged" \
      --homepage "https://github.com/anthonydeseille/flairquery"
  fi
  "${GIT[@]}" clone -q "https://github.com/$SLUG.git" "$WORK" 2>/dev/null
  git -C "$WORK" checkout -q -B main
fi

# the content: everything but .git is replaced
find "$WORK" -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
(cd "$ROOT/demo-app" && tar --exclude=./target -cf - .) | (cd "$WORK" && tar -xf -)
cp "$ROOT/mvnw" "$ROOT/mvnw.cmd" "$WORK/"
mkdir -p "$WORK/.mvn/wrapper" "$WORK/.github/workflows"
cp "$ROOT/.mvn/wrapper/maven-wrapper.properties" "$WORK/.mvn/wrapper/"
printf 'target/\n.idea/\n*.iml\n.DS_Store\n' > "$WORK/.gitignore"

cat > "$WORK/README.md" <<EOF
# FlairQuery demo app (sandbox)

This repository is the demo application of [FlairQuery](https://github.com/anthonydeseille/flairquery), a copy of
its \`demo-app/\` directory. It exists to show what FlairQuery produces: its **pull requests are opened by
FlairQuery**, from fixes it proved on the running application. They are left open on purpose and never merged, so
that the demo keeps its performance traps (listed in [TRAPS.md](TRAPS.md)).

Each pull request carries:
- the fix, generated by a template or by an LLM;
- its proof: the same requests replayed before and after on PostgreSQL, the JSON responses strictly identical,
  fewer SQL statements and less SQL time per request (plans before / after for an index);
- a regression test, proven to fail on the current code and to pass with the fix (the CI below runs it).

Please do not open issues or pull requests here: use the [FlairQuery repository](https://github.com/anthonydeseille/flairquery).

Content: FlairQuery \`demo-app/\` at commit \`$SHA\`. Licensed under the Apache License 2.0, like FlairQuery.
EOF

cat > "$WORK/.github/workflows/ci.yml" <<'EOF'
name: ci

# The demo's tests on every pull request (FlairQuery's regression tests included): Testcontainers PostgreSQL.
on:
  push:
    branches: [main]
  pull_request:

permissions:
  contents: read

jobs:
  test:
    runs-on: ubuntu-latest
    timeout-minutes: 30
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-java@v4
        with:
          distribution: temurin
          java-version: "21"
          cache: maven
      - name: Build and tests
        run: ./mvnw -B verify
EOF
cp "$ROOT/LICENSE" "$WORK/LICENSE"

git -C "$WORK" add -A
if git -C "$WORK" diff --cached --quiet; then
  echo "sandbox $SLUG: main already up to date with demo-app"
  exit 0
fi
git -C "$WORK" -c user.name="FlairQuery" -c user.email="flairquery@invalid" \
  commit -q -m "Demo app of FlairQuery at $SHA"
if [[ "$DRY_RUN" == "--dry-run" ]]; then
  echo "sandbox content assembled in $WORK (dry run: nothing pushed)"
else
  "${GIT[@]}" -C "$WORK" push -q origin main
  echo "sandbox https://github.com/$SLUG: main = demo-app at $SHA"
fi
